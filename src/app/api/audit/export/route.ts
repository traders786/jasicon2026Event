import { NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import { requireAdmin } from '@/lib/auth';
import { getEventContext } from '@/lib/event-context';
import * as XLSX from 'xlsx';

export async function GET(request: Request) {
  try {
    const auth = await requireAdmin();
    if (!auth.authorized) {
      return NextResponse.json({ error: auth.error }, { status: auth.status });
    }

    const { searchParams } = new URL(request.url);
    const eventIdParam = searchParams.get('eventId');

    let targetEventId = eventIdParam;
    if (!targetEventId) {
      const eventCtx = await getEventContext();
      if (eventCtx?.eventId) {
        targetEventId = eventCtx.eventId;
      } else {
        const defaultEvt = await prisma.event.findFirst({
          where: { isActive: true },
          orderBy: { createdAt: 'desc' },
        });
        targetEventId = defaultEvt ? defaultEvt.id : null;
      }
    }

    if (!targetEventId) {
      return NextResponse.json({ error: 'Conference not found' }, { status: 404 });
    }

    const event = await prisma.event.findUnique({
      where: { id: targetEventId },
    });

    if (!event) {
      return NextResponse.json({ error: 'Event not found' }, { status: 404 });
    }

    const baseWhere = {
      registration: {
        eventId: targetEventId,
      },
    };

    // 1. Summary aggregations
    const [
      totalScans,
      successfulScans,
      duplicateScans,
      totalMealsClaimed,
      totalMealsEligible,
    ] = await Promise.all([
      prisma.redemptionLog.count({ where: baseWhere }),
      prisma.redemptionLog.count({ where: { ...baseWhere, result: 'SUCCESS' } }),
      prisma.redemptionLog.count({ where: { ...baseWhere, result: 'ALREADY_REDEEMED' } }),
      prisma.entitlement.count({
        where: {
          category: 'MEAL',
          status: 'REDEEMED',
          registration: { eventId: targetEventId },
        },
      }),
      prisma.entitlement.count({
        where: {
          category: 'MEAL',
          registration: { eventId: targetEventId },
        },
      }),
    ]);

    // 2. Meal breakdown
    const mealEntitlements = await prisma.entitlement.findMany({
      where: {
        category: 'MEAL',
        registration: { eventId: targetEventId },
      },
      select: {
        code: true,
        title: true,
        status: true,
      },
    });

    const mealGroupMap: Record<string, { code: string; title: string; claimed: number; total: number }> = {};
    for (const ent of mealEntitlements) {
      if (!mealGroupMap[ent.code]) {
        mealGroupMap[ent.code] = {
          code: ent.code,
          title: ent.title,
          claimed: 0,
          total: 0,
        };
      }
      mealGroupMap[ent.code].total += 1;
      if (ent.status === 'REDEEMED') {
        mealGroupMap[ent.code].claimed += 1;
      }
    }

    const mealList = Object.values(mealGroupMap).sort((a, b) => a.title.localeCompare(b.title));

    // 3. Scan logs
    const rawLogs = await prisma.redemptionLog.findMany({
      where: baseWhere,
      orderBy: { scannedAt: 'desc' },
      include: {
        registration: {
          include: {
            person: true,
          },
        },
        entitlement: true,
        operator: {
          select: { name: true, role: true },
        },
      },
    });

    const uniqueAttendees = new Set<string>();
    const stationCountMap: Record<string, number> = {};

    rawLogs.forEach((log) => {
      if (log.result === 'SUCCESS' && log.registration?.personId) {
        uniqueAttendees.add(log.registration.personId);
      }
      const st = log.deviceInfo || 'Default Scanner Counter';
      stationCountMap[st] = (stationCountMap[st] || 0) + 1;
    });

    const nowStr = new Date().toLocaleString('en-US', {
      dateStyle: 'medium',
      timeStyle: 'medium',
    });

    // Build Sheet 1: Executive & Meal Summary
    const summaryRows: any[][] = [
      [`${event.title.toUpperCase()} — AUDIT & MEAL REDEMPTION REPORT`],
      [`Venue: ${event.venue}${event.city ? `, ${event.city}` : ''} | Generated: ${nowStr} | Generated By: ${auth.session.name} (${auth.session.role})`],
      [],
      ['EXECUTIVE SCANNING KPI METRICS', ''],
      ['Metric', 'Value'],
      ['Total Scans Conducted', totalScans],
      ['Total Successful Claims', successfulScans],
      ['Duplicate Scans Blocked', duplicateScans],
      ['Total Meals Claimed', totalMealsClaimed],
      ['Total Meals Eligible Across Attendees', totalMealsEligible],
      ['Unique Doctors / Attendees Served', uniqueAttendees.size],
      [],
      ['MEAL CONSUMPTION BREAKDOWN LEDGER', '', '', '', ''],
      ['Meal Code', 'Meal / Session Description', 'Claimed Count', 'Total Eligible', 'Turnout %'],
    ];

    mealList.forEach((m) => {
      const rate = m.total > 0 ? `${Math.round((m.claimed / m.total) * 100)}%` : '0%';
      summaryRows.push([m.code, m.title, m.claimed, m.total, rate]);
    });

    summaryRows.push([]);
    summaryRows.push(['SCANNER COUNTERS & STATIONS LEDGER', '']);
    summaryRows.push(['Counter / Device Name', 'Total Scans Logged']);
    Object.entries(stationCountMap).forEach(([st, cnt]) => {
      summaryRows.push([st, cnt]);
    });

    const wsSummary = XLSX.utils.aoa_to_sheet(summaryRows);
    wsSummary['!cols'] = [
      { wch: 32 },
      { wch: 45 },
      { wch: 18 },
      { wch: 18 },
      { wch: 16 },
    ];

    // Build Sheet 2: Detailed Scan Log
    const detailData = rawLogs.map((log, idx) => {
      const person = log.registration?.person;
      const fullName = person ? `${person.firstName} ${person.lastName}`.trim() : 'Guest Attendee';
      return {
        '#': idx + 1,
        'Scan Timestamp': new Date(log.scannedAt).toLocaleString('en-US', {
          dateStyle: 'medium',
          timeStyle: 'medium',
        }),
        'Doctor / Attendee Name': fullName,
        'Ticket Code': log.registration?.ticketCode || 'N/A',
        'Category / Role': person?.jobTitle || 'Delegate',
        'Phone Number': person?.phone || 'N/A',
        'Hospital / Institution': person?.company || 'N/A',
        'Entitlement Category': log.entitlement?.category || 'GENERAL',
        'Meal / Entitlement Name': log.entitlement?.title || 'Check-in Scan',
        'Scan Outcome': log.result,
        'Scanner Station / Counter': log.deviceInfo || 'Scanner Counter',
        'Operator / Staff': log.operator?.name || 'Staff Desk',
        'Audit Notes': log.notes || '',
      };
    });

    const wsDetails = XLSX.utils.json_to_sheet(detailData);
    wsDetails['!cols'] = [
      { wch: 6 },
      { wch: 24 },
      { wch: 28 },
      { wch: 16 },
      { wch: 18 },
      { wch: 16 },
      { wch: 28 },
      { wch: 16 },
      { wch: 28 },
      { wch: 18 },
      { wch: 24 },
      { wch: 20 },
      { wch: 40 },
    ];

    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, wsSummary, 'Meal & Scan Summary');
    XLSX.utils.book_append_sheet(wb, wsDetails, 'Complete Scan Log');

    const buffer = XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' });
    const safeSlug = event.slug.replace(/[^a-zA-Z0-9_-]/g, '_');
    const dateStamp = new Date().toISOString().split('T')[0];

    return new NextResponse(buffer, {
      status: 200,
      headers: {
        'Content-Type': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        'Content-Disposition': `attachment; filename="${safeSlug}-audit-and-meals-${dateStamp}.xlsx"`,
      },
    });
  } catch (error: unknown) {
    const message = error instanceof Error ? error.message : 'Export failed';
    return NextResponse.json({ error: message }, { status: 500 });
  }
}
